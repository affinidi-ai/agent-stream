#!/bin/bash

# -x Print out all executed commands to the terminal.
# set -x

# -e  Exit immediately if a command exits with a non-zero status.
set -e

source "$(dirname "$0")/_env.sh"
source "$(dirname "$0")/_portable.sh"

# Values the sourced helpers above must provide.
: "${envs_dir:?_env.sh must set envs_dir}"

# Strip --auto-accept from args before positional parsing.
auto_accept=false
_filtered_args=()
for _arg in "$@"; do
  if [[ "${_arg}" == "--auto-accept" ]]; then
    auto_accept=true
  else
    _filtered_args+=("${_arg}")
  fi
done
set -- "${_filtered_args[@]}"

# An interactive prompt needs a terminal on both ends: stdin to read the answer
# and stdout to show the question. If either is redirected (CI, a test harness,
# `make www-rebuild >/dev/null`), the prompt is unanswerable, so auto-accept
# instead of blocking on `read` forever.
if [[ ! -t 0 || ! -t 1 ]]; then
  auto_accept=true
fi

target="$1"
target_dir="$2"

current_dir=$(pwd)
target_dir="${current_dir}/${target_dir}"

# ----------------------------------------------------------------------------
# Port assignment
# ----------------------------------------------------------------------------
# For local-* instances we derive a deterministic port offset from the suffix:
#   - numeric suffix N   → offset = N   (local-1 → 1, local-2 → 2, ...)
#   - non-numeric suffix → offset = 100 + (cksum(suffix) % 900)
#                          (keeps named instances out of the numeric range; 900 slots → low collision chance)
#   - no suffix (envs/local) → offset = 0
# Computed ports are persisted to ${target_dir}/instance.env (kept outside
# config/, which is owned by the service) so run scripts source them
# instead of guessing or scanning.
assign_ports() {
  local dir="$1"
  local base_name
  base_name=$(basename "${dir}")
  local suffix=""
  local offset=0

  if [[ "${base_name}" == local-* ]]; then
    suffix="${base_name#local-}"
  fi

  if [[ -z "${suffix}" ]]; then
    offset=0
  elif [[ "${suffix}" =~ ^[0-9]+$ ]]; then
    offset=$(( suffix ))
  else
    local hash
    hash=$(printf '%s' "${suffix}" | cksum | awk '{print $1}')
    offset=$(( 100 + (hash % 900) ))
  fi

  http_port=$(( DEFAULT_HTTP_PORT + offset ))
  https_port=$(( DEFAULT_HTTPS_PORT + offset ))
  outbound_port=$(( DEFAULT_OUTBOUND_PORT + offset ))
  frontend_port=$(( DEFAULT_FRONTEND_PORT + offset ))

  # Collision check: scan all sibling local-*/instance.env files.
  local f other_http other_https other_outbound other_frontend
  for f in "${envs_dir}"/local-*/instance.env "${envs_dir}"/local/instance.env; do
    [[ -f "${f}" ]] || continue
    [[ "${f}" == "${dir}/instance.env" ]] && continue
    [[ "${f}" == *".bak/"* ]] && continue
    other_http=$(grep -E '^HTTP_PORT='     "${f}" | cut -d= -f2)
    other_https=$(grep -E '^HTTPS_PORT='   "${f}" | cut -d= -f2)
    other_outbound=$(grep -E '^OUTBOUND_PORT=' "${f}" | cut -d= -f2)
    other_frontend=$(grep -E '^FRONTEND_PORT=' "${f}" | cut -d= -f2)
    if [[ "${other_http}" == "${http_port}" \
       || "${other_https}" == "${https_port}" \
       || "${other_outbound}" == "${outbound_port}" \
       || "${other_frontend}" == "${frontend_port}" ]]; then
      echo "❌ Port collision with ${f}:"
      echo "   wanted   HTTP=${http_port} HTTPS=${https_port} OUTBOUND=${outbound_port} FRONTEND=${frontend_port}"
      echo "   existing HTTP=${other_http} HTTPS=${other_https} OUTBOUND=${other_outbound} FRONTEND=${other_frontend}"
      echo "   Pick a different suffix (x=...) or remove the conflicting env."
      exit 1
    fi
  done

  mkdir -p "${dir}"
  cat > "${dir}/instance.env" <<EOF
# Generated by scripts/_prepare.sh — do not edit by hand.
HTTP_PORT=${http_port}
HTTPS_PORT=${https_port}
OUTBOUND_PORT=${outbound_port}
FRONTEND_PORT=${frontend_port}
EOF
  echo "🔢 Ports for $(basename "${dir}"): HTTP=${http_port} HTTPS=${https_port} OUTBOUND=${outbound_port} FRONTEND=${frontend_port}"
}

# Prints the connection details a tunnel/proxy needs to expose <public_url>.
# Usage: show_proxy_info <public_url> <local_port>
show_proxy_info() {
  local url="$1" port="$2"

  local ws_label="🔌 Server (WebSocket):"
  local pt_label="🔢 Proxy port:"
  local gw_label="🌐 Gateway public URL:"
  local _lmax=${#ws_label}
  (( ${#pt_label} > _lmax )) && _lmax=${#pt_label}
  (( ${#gw_label} > _lmax )) && _lmax=${#gw_label}

  echo ""
  printf '\033[0;32m📋 Tunnel connection details - use these when configuring a tunnel or proxy:\033[0m\n'
  printf "   %-${_lmax}s  %s\n" "${ws_label}" "ws://localhost:${port}"
  printf "   %-${_lmax}s  \033[1;33m%s\033[0m\n" "${pt_label}" "${port}"
  printf "   %-${_lmax}s  %s\n" "${gw_label}" "${url}"
  echo ""
}

# Default ports for non-local targets (docker, etc.)
http_port=${3:-8080}
https_port=${4:-8443}
outbound_port=${DEFAULT_OUTBOUND_PORT}
frontend_port=${DEFAULT_FRONTEND_PORT}

if [[ "${target_dir}" == *"/local"* ]]; then
  assign_ports "${target_dir}"
fi

echo "📦 Preparing ${target} env ${target_dir}..."

(mkdir -p "${target_dir}" && echo "✅ ${target_dir} directory created") || echo "✅ ${target_dir} directory exist"

if [[ ! -f "${target_dir}/certs/cert.pem" ]]
then
  pushd "${target_dir}"
  cp -r "${current_dir}/envs/certs" .
  popd
fi

regenerate_config_toml=false
config_toml="${target_dir}/config/config.toml"
previous_auth_mode=""

if [[ ! -f "${config_toml}" ]]
then
  regenerate_config_toml=true
else
  missing_field=""
  if ! grep -qE '^limits[[:space:]]*=' "${config_toml}"
  then
    missing_field="config_files.limits"
  elif ! grep -qE '^backup_encryption_key[[:space:]]*=' "${config_toml}"
  then
    missing_field="backup_encryption_key"
  elif ! awk '
      /^\[/ { in_encryption = ($0 == "[encryption]") }
      in_encryption && /^(enabled|allow_unencrypted)[[:space:]]*=[[:space:]]*true/ { found = 1 }
      END { exit !found }
    ' "${config_toml}"
  then
    if [[ -d "${target_dir}/_storage" ]]
    then
      # Storage written before the choice existed is unencrypted, and governance logs and
      # multimedia blobs cannot be migrated: keep it readable with an explicit opt-out.
      echo "⚠️  ${config_toml} has no encryption-at-rest choice and ${target_dir}/_storage exists; adding [encryption] allow_unencrypted = true. See docs/ENCRYPTION_AT_REST.md to encrypt it."
      awk '{ print } $0 == "[encryption]" && !done { print "allow_unencrypted = true"; done = 1 }
           END { if (!done) printf "\n[encryption]\nallow_unencrypted = true\n" }' \
        "${config_toml}" > "${config_toml}.tmp" && mv "${config_toml}.tmp" "${config_toml}"
    else
      missing_field="an encryption-at-rest choice ([encryption] enabled or allow_unencrypted)"
    fi
  fi

  if [[ -n "${missing_field}" ]]
  then
    echo "⚠️  Existing config.toml is missing ${missing_field}. Backing it up to config.toml.bak and regenerating it."
    if [[ "${auto_accept}" != "true" ]]; then
      printf "⏎  Press Enter to continue... "
      read -r _pause
    fi
    previous_auth_mode=$(grep -E '^auth_mode[[:space:]]*=' "${config_toml}" | sed -E 's/^auth_mode[[:space:]]*=[[:space:]]*"([^"]+)"/\1/' || true)
    cp "${config_toml}" "${config_toml}.bak"
    regenerate_config_toml=true
  fi
fi

if [[ "${regenerate_config_toml}" == "true" ]]
then
  mkdir -p "${target_dir}/config"

  if [[ "${target_dir}" == *"/local"* ]]
  then
    echo "🦀 Building debug binary for bootstrap generation..."
    cargo build

    # ${agent_name}
    ./target/debug/agent-stream \
      --generate-bootstrap \
      --base-folder "${target_dir}" \
      --cors-origins "http://localhost:${http_port},http://127.0.0.1:${http_port},http://0.0.0.0:${http_port},http://localhost:${frontend_port}" > "${target_dir}/config/config.toml"
  fi

  if [[ "${target_dir}" == *"/docker"* ]]
  then
    # Generated with the image itself, so the Docker path needs no host Rust
    # toolchain. Paths are container paths under /app.
    if ! docker image inspect "${tag}" >/dev/null 2>&1; then
      echo "❌ Docker image ${tag} not found. Build it first: make docker-build-local"
      exit 1
    fi
    docker run --rm "${tag}" \
      --generate-bootstrap \
      --base-folder "/app" \
      --cors-origins "http://localhost:8080,http://127.0.0.1:8080,http://0.0.0.0:8080,https://localhost:8443" > "${target_dir}/config/config.toml"
  fi

  if [[ -n "${previous_auth_mode}" ]]
  then
    sedi "s/^auth_mode = \".*\"/auth_mode = \"${previous_auth_mode}\"/" "${config_toml}"
    echo "✅ auth_mode re-applied: ${previous_auth_mode}"
  fi
fi

# The local mediator's did:webvh / did:web lives on localhost, which DID
# resolution refuses unless [did_cache] allow_private_hosts is on.
if [[ ! -f "${config_toml}" ]]
then
  :
elif [[ "${regenerate_config_toml}" == "true" ]]
then
  sedi -E 's/^allow_private_hosts[[:space:]]*=.*/allow_private_hosts = true/' "${config_toml}"
elif ! grep -qE '^allow_private_hosts[[:space:]]*=' "${config_toml}"
then
  if grep -qE '^\[did_cache\]' "${config_toml}"
  then
    awk '{ print } $0 == "[did_cache]" { print "allow_private_hosts = true" }' "${config_toml}" > "${config_toml}.tmp"
    mv "${config_toml}.tmp" "${config_toml}"
  else
    printf '\n[did_cache]\nallow_private_hosts = true\n' >> "${config_toml}"
  fi
  echo "✅ [did_cache] allow_private_hosts enabled for the local mediator"
fi

if [[ ! -f "${target_dir}/config/agent-stream.json" ]]
then
  # Determine which template to use (all local* instances share the local template)
  if [[ "${target_dir}" == *"/local"* ]]
  then
    gateway_template="local"
  elif [[ "${target_dir}" == *"/docker"* ]]
  then
    gateway_template="docker"
  else
    gateway_template="${target_dir}"
  fi

  gateway_url=""         # full URL as entered, e.g. https://example.com:8443
  gateway_domain=""      # hostname only — no scheme, no port (used for rp_id)
  gateway_domain_port="" # host:port — no scheme (used for did.domain)
  if [[ "${target_dir}" == *"/local"* ]]
  then
    if [[ "${auto_accept}" == "true" ]]; then
      gateway_url=""
    else
      printf "🌐 Enter public URL for this gateway (e.g. https://agent-stream.example.com, leave empty for localhost): "
      read -r gateway_url
    fi
    if [[ -n "${gateway_url}" ]]
    then
      # Strip scheme (https:// or http://) then strip any path, then strip :port
      gateway_domain="${gateway_url#*://}"
      gateway_domain="${gateway_domain%%/*}"
      gateway_domain_port="${gateway_domain}"   # keep port for did.domain
      gateway_domain="${gateway_domain%%:*}"

      show_proxy_info "${gateway_url}" "${http_port}"
      if [[ "${auto_accept}" != "true" ]]; then
        printf "⏎  Press Enter to continue... "
        read -r _pause
      fi
    fi
  fi

  cp config/examples/agent-stream.example.json "${target_dir}/config/agent-stream.json"

  if [[ "${gateway_template}" == "local" ]]
  then
    # Replace default ports with the instance-specific ports
    sedi "s/\"port\": 8080/\"port\": ${http_port}/g" "${target_dir}/config/agent-stream.json"
    sedi "s/\"port\": 8443/\"port\": ${https_port}/g" "${target_dir}/config/agent-stream.json"
    sedi "s/\"port\": 9000/\"port\": ${outbound_port}/g" "${target_dir}/config/agent-stream.json"
    sedi "s|http://localhost:8080|http://localhost:${http_port}|g" "${target_dir}/config/agent-stream.json"
    sedi "s|https://localhost:8443|https://localhost:${https_port}|g" "${target_dir}/config/agent-stream.json"
    sedi "s|https://localhost:9000|https://localhost:${outbound_port}|g" "${target_dir}/config/agent-stream.json"
    if [[ -n "${gateway_url}" ]]
    then
      # did.domain — host:port, no scheme
      sedi "s|\"domain\": \"YOUR_DOMAIN\"|\"domain\": \"${gateway_domain_port}\"|g" "${target_dir}/config/agent-stream.json"
      # webauthn.rp_id — hostname only, no scheme, no port
      sedi "s|\"rp_id\": \"YOUR_DOMAIN\"|\"rp_id\": \"${gateway_domain}\"|g" "${target_dir}/config/agent-stream.json"
      # webauthn.external_origin — full URL with port (same as did.domain)
      sedi "s|\"external_origin\": \"https://YOUR_DOMAIN\"|\"external_origin\": \"${gateway_url}\"|g" "${target_dir}/config/agent-stream.json"
      # listener external_urls — replace the template placeholder full URL (HTTP listener)
      sedi "s|https://YOUR_DOMAIN|${gateway_url}|g" "${target_dir}/config/agent-stream.json"
      # Also inject the proxy URL into the HTTPS listener so /.well-known/did.json
      # resolves correctly when served through the proxy tunnel (HTTPS port).
      sedi "s|\"https://localhost:${https_port}\"|\"${gateway_url}\", \"https://localhost:${https_port}\"|g" "${target_dir}/config/agent-stream.json"
    else
      # webauthn.rp_id must be a real domain (or "localhost") — leaving it as
      # the template placeholder fails effective_domain validation at startup.
      sedi "s|\"rp_id\": \"YOUR_DOMAIN\"|\"rp_id\": \"localhost\"|g" "${target_dir}/config/agent-stream.json"
      # WebAuthn external_origin must match the frontend dev server origin
      # (frontend_port was set above by assign_ports for /local targets)
      sedi "s|\"external_origin\": \"https://YOUR_DOMAIN\"|\"external_origin\": \"http://localhost:${frontend_port}\"|g" "${target_dir}/config/agent-stream.json"
    fi
  fi

  if [[ "${gateway_template}" == "docker" ]]
  then
    # Docker local evaluation: resolve the WebAuthn / DID placeholders to
    # localhost so `docker compose up` and `make docker-run` start without
    # hand-editing agent-stream.json. The external_origin must match the URL
    # the browser opens for passkey login; docker-compose.yml serves the
    # dashboard over TLS at https://localhost:8443, so pin it there. For a real
    # deployment, override webauthn.rp_id, webauthn.external_origin and
    # did.domain with your public host.
    docker_domain="localhost"
    docker_url="https://localhost:8443"
    sedi "s|\"domain\": \"YOUR_DOMAIN\"|\"domain\": \"${docker_domain}\"|g" "${target_dir}/config/agent-stream.json"
    sedi "s|\"rp_id\": \"YOUR_DOMAIN\"|\"rp_id\": \"${docker_domain}\"|g" "${target_dir}/config/agent-stream.json"
    sedi "s|\"external_origin\": \"https://YOUR_DOMAIN\"|\"external_origin\": \"${docker_url}\"|g" "${target_dir}/config/agent-stream.json"
    sedi "s|\"https://YOUR_DOMAIN\",||g" "${target_dir}/config/agent-stream.json"
    sedi "s|https://YOUR_DOMAIN|${docker_url}|g" "${target_dir}/config/agent-stream.json"
  fi
fi

# Docker quickstart seed: a fresh envs/docker gets an LLM Surface routed to the
# mock model server in docker-compose.yml. Existing storage is never touched.
if [[ "${target_dir}" == *"/docker"* && ! -d "${target_dir}/_storage" ]]
then
  mkdir -p "${target_dir}/_storage"
  cp -R "${current_dir}/deploy/quickstart/seed/storage/." "${target_dir}/_storage/"
  echo "✅ Seeded ${target_dir}/_storage with the quickstart LLM Surface (/llm/quickstart)"
fi

# Where a dashboard restore stages backup.asbak; mounted so it survives the
# restart that applies it.
if [[ "${target_dir}" == *"/docker"* ]]
then
  mkdir -p "${target_dir}/_backup_restore"
fi

# Docker Engine on Linux applies host ownership to bind mounts as-is, so the
# container user (uid ${container_uid}) could neither write _storage or
# _backup_restore nor read the 0600 TLS key. Hand them to that uid. Docker
# Desktop (macOS) maps ownership itself and needs nothing.
if [[ "${target_dir}" == *"/docker"* && "$(uname -s)" == "Linux" ]]
then
  _owned_paths=("${target_dir}/_storage" "${target_dir}/_backup_restore" "${target_dir}/certs")
  _needs_chown=false
  for _p in "${_owned_paths[@]}"; do
    [[ "$(stat -c '%u' "${_p}")" == "${container_uid}" ]] || _needs_chown=true
  done
  if [[ "${_needs_chown}" == "true" ]]; then
    _sudo=""
    [[ "$(id -u)" == "0" ]] || _sudo="sudo"
    echo "🔐 Giving ${target_dir}/_storage, _backup_restore and certs to the container user (uid ${container_uid})${_sudo:+, which needs sudo}..."
    if ${_sudo} chown -R "${container_uid}:${container_uid}" "${_owned_paths[@]}"; then
      echo "✅ ${target_dir}/_storage, _backup_restore and certs owned by uid ${container_uid}"
    else
      echo "❌ Could not change ownership. Run it yourself, then start the container:" >&2
      echo "   sudo chown -R ${container_uid}:${container_uid} ${_owned_paths[*]}" >&2
      exit 1
    fi
  fi
fi

# Always (re)apply the dashboard static path for local envs so a stale path
# from a previous run can never be served. Idempotent: matches both the
# template placeholder ("www") and any previously-rewritten absolute path
# pointing at www, www/build, or www/default/build.
if [[ "${target_dir}" == *"/local"* && -f "${target_dir}/config/agent-stream.json" ]]
then
  expected_path="${current_dir}/${WWW_DIR:-www/default}/build"
  gateway_json="${target_dir}/config/agent-stream.json"

  if ! command -v jq >/dev/null 2>&1; then
    echo "❌ jq is required to update dashboard static path. Install with: brew install jq"
    exit 1
  fi

  updated=$(jq --arg expected "${expected_path}" '
    walk(
      if type == "object"
         and .type == "static"
         and (.path | type == "string")
         and (.path == "www" or (.path | test("/www(/build|/default/build)?$")))
      then .path = $expected
      else .
      end
    )
  ' "${gateway_json}")

  if [[ "${updated}" != "$(cat "${gateway_json}")" ]]; then
    printf '%s\n' "${updated}" > "${gateway_json}"
    echo "✅ dashboard static path → ${expected_path}"
  else
    echo "✅ dashboard static path already at ${expected_path}"
  fi
fi

if [[ ! -f "${target_dir}/marketplace-models.json" ]]
then
  cp ./config/examples/marketplace-models.example.json "${target_dir}/config/marketplace-models.json"
fi

if [[ ! -f "${target_dir}/config/metrics.json" ]]
then
  cp ./config/examples/metrics.example.json "${target_dir}/config/metrics.json"
fi

if [[ ! -f "${target_dir}/config/llm.json" ]]
then
  cp ./config/examples/llm.example.json "${target_dir}/config/llm.json"
fi

if [[ ! -f "${target_dir}/config/prompt-guard.json" ]]
then
  cp ./config/examples/prompt-guard.example.json "${target_dir}/config/prompt-guard.json"
fi

if [[ ! -f "${target_dir}/config/rbac.json" ]]
then
  cp ./config/examples/rbac.example.json "${target_dir}/config/rbac.json"
fi

if [[ ! -f "${target_dir}/config/saml.json" ]]
then
  cp ./config/examples/saml.example.json "${target_dir}/config/saml.json"
fi

if [[ ! -f "${target_dir}/marketplace-models.json" ]]
then
  cp ./config/examples/marketplace-models.example.json "${target_dir}/config/marketplace-models.json"
fi

if [[ ! -d "${target_dir}/config/surface_templates" ]]
then
  cp -r ./config/examples/surface_templates "${target_dir}/config/surface_templates"
fi

if [[ ! -d "${target_dir}/config/defaults" ]]
then
  cp -r ./config/examples/defaults "${target_dir}/config/defaults"
fi

# Persist URL_LOCAL (always localhost) and URL_PROXY (gateway_url when
# provided) to instance.env so 'make testkit-* x=<name> h=l|h=p' can resolve
# the correct URL without guessing.
if [[ "${target_dir}" == *"/local"* ]]; then
  _testkit_local="http://localhost:${http_port}"
  if grep -q '^URL_LOCAL=' "${target_dir}/instance.env" 2>/dev/null; then
    sedi "s|^URL_LOCAL=.*|URL_LOCAL=${_testkit_local}|" "${target_dir}/instance.env"
  else
    echo "URL_LOCAL=${_testkit_local}" >> "${target_dir}/instance.env"
  fi
  echo "🧪 URL_LOCAL → ${_testkit_local}"

  if [[ -n "${gateway_url}" ]]; then
    if grep -q '^URL_PROXY=' "${target_dir}/instance.env" 2>/dev/null; then
      sedi "s|^URL_PROXY=.*|URL_PROXY=${gateway_url}|" "${target_dir}/instance.env"
    else
      echo "URL_PROXY=${gateway_url}" >> "${target_dir}/instance.env"
    fi
    echo "🧪 URL_PROXY → ${gateway_url}"
  else
    # Derive proxy URL from .did.domain in agent-stream.json when no gateway_url was given.
    _proxy_url=""
    if [[ -f "${target_dir}/config/agent-stream.json" ]]; then
      _domain=$(jq -r '.did.domain // empty' "${target_dir}/config/agent-stream.json" 2>/dev/null)
      [[ -n "${_domain}" ]] && _proxy_url="https://${_domain}"
    fi
    if grep -q '^URL_PROXY=' "${target_dir}/instance.env" 2>/dev/null; then
      sedi "s|^URL_PROXY=.*|URL_PROXY=${_proxy_url}|" "${target_dir}/instance.env"
    else
      echo "URL_PROXY=${_proxy_url}" >> "${target_dir}/instance.env"
    fi
    [[ -n "${_proxy_url}" ]] && echo "🧪 URL_PROXY → ${_proxy_url}"
  fi
fi

echo "✅ ${target} env ${target_dir} preparation completed!"
